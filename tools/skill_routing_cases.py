def get_cases(phase):
    """Return a fresh fixed split. No model output is ever appended to dialogue."""
    if phase not in ('development', 'holdout'):
        raise ValueError('phase must be development or holdout')
    return deepcopy([case for case in _build_cases() if case['phase'] == phase])
