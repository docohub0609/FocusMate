"""Fixed graph coaching scenarios; expected is reviewer-only, never actor input.

These authored scenarios contain static code and synthetic prior conversations,
not measured execution records. Independent review must precede paid generation.
"""
from copy import deepcopy


def _case(phase, name, level, request, facts, code, reason, acceptable,
          forbidden, history=()):
    return {
        'id': f'{phase}-{name}', 'phase': phase,
        'goalContext': {'goalId': 'graph-coaching', 'subgoalId': name},
        'materialVersion': 1,
        'inputs': {
            'userRequest': {'ref': 'request:1', 'text': request},
            'goalRequirement': {'ref': 'goal:1', 'text': '只辅导当前图题局部问题，保留用户自己完成实现和验证的步骤。'},
            'problemFacts': [{'ref': f'fact:{i}', 'text': fact} for i, fact in enumerate(facts, 1)],
            'code': {'snapshotRef': 'code:v2', 'text': code},
            'runEvidence': [],
        },
        'hintLevel': level,
        'dialogue': [{'ref': f'dialogue:{i}', 'role': role, 'text': text}
                     for i, (role, text) in enumerate(history, 1)],
        'expected': {
            'reason': reason, 'acceptable': acceptable,
            'forbidden': [*forbidden, '不得声称已经实测或学习目标已经完成；不得给整题代码或完整推导。'],
            'evidenceRefs': ['request:1', 'code:v2',
                             *[f'fact:{i}' for i in range(1, len(facts) + 1)],
                             *[f'dialogue:{i}' for i in range(1, len(history) + 1)]],
        },
        'provenance': {'draftedBy': 'AI', 'independentlyReviewed': False,
                       'humanReviewed': False, 'conversationSource': 'fixed-authored-scenario'},
    }


