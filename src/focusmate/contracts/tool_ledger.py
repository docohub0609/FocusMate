"""Persistence port used by core; concrete stores live in adapters."""
from typing import Protocol


class ToolLedger(Protocol):
    def start_call(self, loop_id: str, context: str, call_id: str, request: str) -> tuple[int, list[tuple[str, str | None]]] | None: ...
    def reserve_run(self, loop_id: str, identity: str) -> bool: ...
    def finish_call(self, identity: int, result: str) -> None: ...
