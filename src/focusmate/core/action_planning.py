def review_issues(review,candidate):
    """Extract checked failures; identity and original text are not regenerated by a model."""
    digest=hash_content(candidate).split(':')[-1][:16]
    return [{'issueId':f'issue-{digest}-{key}','sourceCheck':key,
             'candidateHash':hash_content(candidate),**deepcopy(review['checks'][key])}
            for key in REVIEW_KEYS if review['checks'][key]['verdict']=='fail']

def validate_action_candidate(value,bundle,diagnosis,extras=(),*,runtime_goals=None):
    try:Draft202012Validator(CANDIDATE_SCHEMA).validate(value)
    except Exception:raise ValueError('INVALID_ACTION_FORMAT') from None
    req=bundle['request'];by={r['ref']:r for r in bundle['records']+list(extras)}
    contract=by[req['contractRef']]['content'];ids={s['subgoalId'] for s in (runtime_goals if runtime_goals is not None else contract['subgoals'])}
    questions={q['questionKey'] for q in diagnosis['questions']}
    if not set(value['questionKeys'])<=questions or not set(value['subgoalIds'])<=ids:raise ValueError('INVALID_ACTION_TARGET')
    if req['goalContext'].get('subgoalId') and set(value['subgoalIds'])-{req['goalContext']['subgoalId']}:
        raise ValueError('INVALID_ACTION_SCOPE')
    if not set(value['evidenceRefs'])<=by.keys():raise ValueError('INVALID_ACTION_REFERENCE')
    for c in value['diagnosisCorrections']:
        if c['questionKey'] not in questions or not set(c['evidenceRefs'])<=by.keys():raise ValueError('INVALID_DIAGNOSIS_CORRECTION')
    for q in value['requestQuotes']:
        if q['ref']!=req['userRequestRef'] or q['text'] not in by[q['ref']]['content']['text']:raise ValueError('INVALID_PERMISSION_QUOTE')
    if value['answerScope']=='fullSolution' and (contract['coachPolicy']!=REQUEST_POLICY or not value['requestQuotes']):
        raise ValueError('FULL_SOLUTION_NOT_AUTHORIZED')
    f=value['followUp']
    if f['kind']!='none' and not f['expectedUserAction'].strip():raise ValueError('MISSING_EXPECTED_USER_ACTION')
    if not set(f['criterionIds'])<=set(value['subgoalIds']):raise ValueError('INVALID_FOLLOWUP_TARGET')
    if f['kind']=='awaitEvidence':
        if not f['criterionIds'] or not f['checks']:raise ValueError('MISSING_VERIFICATION_DIRECTION')
    elif f['checks'] or f['criterionIds']:raise ValueError('UNNECESSARY_VERIFICATION')
    return deepcopy(value)

def validate_action_review(value,candidate,refs,*,previous_issues=()):
    try:Draft202012Validator(REVIEW_SCHEMA).validate(value)
    except Exception:raise ValueError('INCOMPLETE_ACTION_REVIEW') from None
    texts=[candidate['content'],candidate['reason'],candidate['followUp']['reason'],candidate['followUp']['expectedUserAction']]
    texts += [c['reason'] for c in candidate['diagnosisCorrections']]
    texts += [q['text'] for q in candidate['requestQuotes']]
    for item in value['checks'].values():
        if not set(item['materialRefs'])<=set(refs):raise ValueError('INVALID_REVIEW_REFERENCE')
        q=item['candidateQuote']
        if q and not any(q in text for text in texts):raise ValueError('INVALID_REVIEW_QUOTE')
        if item['verdict']=='fail' and not q:raise ValueError('MISSING_ERROR_LOCATION')
    verdicts={c['verdict'] for c in value['checks'].values()}
    expected={i['issueId'] for i in previous_issues}
    revisited=value.get('issueChecks',[])
    if len(revisited)!=len(expected) or {i['issueId'] for i in revisited}!=expected:
        raise ValueError('INCOMPLETE_ISSUE_REVIEW')
    for item in revisited:
        if not set(item['materialRefs'])<=set(refs):raise ValueError('INVALID_REVIEW_REFERENCE')
        if item['status']=='stillPresent':verdicts.add('fail')
        if item['status']=='uncertain':verdicts.add('uncertain')
    return 'uncertain' if 'uncertain' in verdicts else 'failed' if 'fail' in verdicts else 'passed'

def review_transition(review,candidate,refs,*,repaired,remaining_model_calls,previous_issues=()):
    """Choose a next step, never perform it or allocate another request budget."""
    verdict=validate_action_review(review,candidate,refs,previous_issues=previous_issues)
    if verdict=='passed':return 'accept'
    if verdict=='uncertain':return 'uncertain'
    return 'repair' if not repaired and remaining_model_calls>=2 else 'reject'


def action_from_candidate(candidate,bundle,diagnosis,*,action_id,created_at):
    return {'schemaVersion':'2.0.0','actionId':action_id,'createdAt':created_at,
        'goalContext':deepcopy(bundle['request']['goalContext']),'contractVersion':bundle['request']['contractVersion'],
        'diagnosisId':diagnosis['diagnosisId'],'userRequestRef':bundle['request']['userRequestRef'],
        'codeSnapshotRef':bundle['request'].get('currentCodeRef'),'status':'proposed',
        'semanticStatus':'modelReviewedNotVerified','candidateHash':hash_content(candidate),**deepcopy(candidate)}


def planning_report(state):
    from focusmate.contracts.schema_validation import validate
    r=state['rounds'][state['currentRoundId']]
    published=next((x for x in state['outbox'] if x['roundId']==r['roundId']),None)
    report={'schemaVersion':'1.0.0','sessionId':state['sessionId'],'roundId':r['roundId'],
        'goalContext':deepcopy(state['goalContext']),'contractVersion':state['contractVersion'],
        'status':'accepted' if published else 'notCompleted','failure':r['failure'],
        'action':deepcopy(published['learningAction']) if published else None,
        'stepIds':[s['stepId'] for s in state['steps'].values() if s['roundId']==r['roundId']],
        'semanticStatus':'notLearningVerification'}
    validate('ActionPlanningReport',report)
    return report
